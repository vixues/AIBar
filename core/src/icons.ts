const ALIASES: Readonly<Record<string, string>> = {
  '?': 'circle-help',
  attach: 'paperclip',
  help: 'circle-help',
  'help-circle': 'circle-help',
  trash: 'trash-2',
};

const LUCIDE_NAME = /^[a-z][a-z0-9-]*$/;
const cache = new Map<string, IconRenderable>();

/**
 * Map a named Lucide ref (or a 1–2 grapheme glyph) to a renderable.
 * Unknown kebab-case names get a generic circle instead of a truncated letter.
 */
export function resolveDefaultIcon(ref: string): IconRenderable {
  const raw = ref.trim();
  const cached = cache.get(raw);
  if (cached) return cached;

  const chars = Array.from(raw);
  if (chars.length === 0) {
    const empty = { kind: 'text' as const, text: '·' };
    cache.set(raw, empty);
    return empty;
  }

  let key = raw.toLowerCase();
  if (key.startsWith('lucide:')) key = key.slice('lucide:'.length);
  if (key.startsWith('provider:')) {
    const letter = (key.slice('provider:'.length).trim().charAt(0) || '·').toUpperCase();
    const icon = { kind: 'text' as const, text: letter };
    cache.set(raw, icon);
    return icon;
  }

  key = ALIASES[key] ?? key;
  const inner = ICONS[key];
  if (inner) {
    const icon = lucide(inner);
    cache.set(raw, icon);
    return icon;
  }

  // Keep emoji / short glyphs intact (String.slice can split a surrogate pair).
  if (chars.length <= 2 && !LUCIDE_NAME.test(raw)) {
    const icon = { kind: 'text' as const, text: chars.join('') };
    cache.set(raw, icon);
    return icon;
  }

  const fallback = lucide(ICONS.circle!);
  cache.set(raw, fallback);
  return fallback;
}
